"""Run the classifier evaluation and write eval/results.md and eval/results.json.

    python eval/run_eval.py              # classify (cached) and score; needs ANTHROPIC_API_KEY
    python eval/run_eval.py --offline    # score from the classification cache only
    python eval/run_eval.py --freeze     # record label hashes in eval/labels.lock

Every number in results.md comes from this run. Results are marked PROVISIONAL while
any label file is still a draft (not yet reviewed by a person).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import logging
import sys
from dataclasses import asdict
from pathlib import Path
from typing import Any

from agentcapmap import __version__
from agentcapmap.classify import Classifier
from agentcapmap.classify.cache import ClassificationCache
from agentcapmap.classify.prompt import PROMPT_VERSION
from agentcapmap.evaluation import (
    AxisMetrics,
    ClassifierReport,
    PlantedRecall,
    RuleAgreement,
    label_manifest,
    label_status,
    load_labeled_servers,
    manifest_digest,
    planted_recall,
    rule_agreement,
    score_classifier,
)
from agentcapmap.models import ToolClassification, ToolDefinition
from agentcapmap.policy import load_policy
from agentcapmap.taxonomy import AXES, TAXONOMY_VERSION

EVAL_DIR = Path(__file__).resolve().parent
ROOT = EVAL_DIR.parent
LABELS = EVAL_DIR / "labeled_servers"
LOCK = EVAL_DIR / "labels.lock"


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _check_frozen(manifest: dict[str, str], allow_changes: bool) -> str:
    if not LOCK.is_file():
        return "not frozen (run with --freeze once labels are final)"
    frozen = json.loads(LOCK.read_text(encoding="utf-8"))
    if frozen != manifest:
        changed = sorted(
            set(frozen) ^ set(manifest) | {k for k in frozen if frozen.get(k) != manifest.get(k)}
        )
        if not allow_changes:
            sys.exit(
                f"labels changed since freezing: {', '.join(changed)} (use --allow-label-changes)"
            )
        return f"CHANGED since freezing: {', '.join(changed)}"
    return f"frozen ({manifest_digest(manifest)[:12]})"


def _axis_table(axes: dict[str, AxisMetrics]) -> list[str]:
    lines = [
        "| Axis | Accuracy | Macro-F1 | Detection precision | Detection recall | Detection F1 |",
        "|---|---|---|---|---|---|",
    ]
    for axis in AXES:
        m = axes[axis]
        d = m.detection
        lines.append(
            f"| `{axis}` | {_pct(m.accuracy)} | {_pct(m.macro_f1)} | {_pct(d.precision)} | "
            f"{_pct(d.recall)} | {_pct(d.f1)} |"
        )
    return lines


def _confusion(m: AxisMetrics) -> list[str]:
    predicted = list(next(iter(m.confusion.values())).keys())
    lines = [
        f"| truth \\ predicted | {' | '.join(predicted)} |",
        "|---|" + "---|" * len(predicted),
    ]
    for truth, row in m.confusion.items():
        lines.append(f"| **{truth}** | {' | '.join(str(row[p]) for p in predicted)} |")
    return lines


def write_results(
    *,
    out: Path,
    report: ClassifierReport,
    agreement: RuleAgreement,
    planted: PlantedRecall,
    meta: dict[str, Any],
) -> None:
    provisional = meta["label_status"].get("draft", 0) or meta["label_status"].get("unlabeled", 0)
    banner = (
        "> [!WARNING]\n> **PROVISIONAL.** Some labels are AI-drafted and not yet reviewed by a "
        "person, so these numbers are not a valid benchmark. Do not quote them.\n"
        if provisional
        else ""
    )
    lines = [
        "# Evaluation results",
        "",
        banner,
        "Generated by `python eval/run_eval.py`. Do not edit numbers by hand.",
        "",
        "| | |",
        "|---|---|",
        f"| Date | {meta['date']} |",
        f"| agent-capmap | {meta['tool_version']} |",
        f"| Model | `{meta['model']}` (served: {', '.join(meta['served_models']) or 'n/a'}) |",
        f"| Prompt / taxonomy version | {PROMPT_VERSION} / {TAXONOMY_VERSION} |",
        f"| Labels | {meta['servers']} servers, {report.tools} tools; "
        f"status {dict(meta['label_status'])}; {meta['frozen']} |",
        f"| Unclassified | {report.unclassified} of {report.tools} tools |",
        "",
        "## Headline",
        "",
        f"- **Exact-match accuracy (all six tags right): {_pct(report.exact_match)}**",
        f"- **Planted-risk recall on fixtures: {_pct(planted.recall)}** "
        f"({planted.detected}/{planted.planted} classifier-dependent findings)",
        f"- **False-positive rate on clean agents: {_pct(agreement.false_positive_rate)}** "
        f"({agreement.false_alarm_agents}/{agreement.clean_agents} agents with no critical/high "
        "finding under ground truth got one from predicted tags)",
        f"- Rule-level agreement on {agreement.agents} realistic agents: precision "
        f"{_pct(agreement.precision)}, recall {_pct(agreement.recall)}",
        "",
        "## Per-axis results",
        "",
        "Detection = the tool has any non-default value on the axis.",
        "",
        *_axis_table(report.axes),
        "",
        f"Suspicious-description flag: precision {_pct(report.suspicious.precision)}, recall "
        f"{_pct(report.suspicious.recall)} (support {report.suspicious.support}).",
        "",
        "## Confusion matrices",
        "",
        "### egress",
        "",
        *_confusion(report.axes["egress"]),
        "",
        "### execution",
        "",
        *_confusion(report.axes["execution"]),
        "",
        "## Rule agreement per agent",
        "",
        "| Agent | Servers | Ground truth | Predicted |",
        "|---|---|---|---|",
        *(
            f"| {a['agent']} | {', '.join(a['servers'])} | {', '.join(a['truth']) or '-'} | "
            f"{', '.join(a['predicted']) or '-'} |"
            for a in agreement.per_agent
        ),
        "",
        "## Planted risks",
        "",
        "| Fixture | Planted | Detected |",
        "|---|---|---|",
        *(
            f"| {name} | {', '.join(v['planted'])} | {', '.join(v['detected']) or '-'} |"
            for name, v in planted.per_fixture.items()
        ),
        "",
        "## Disagreements",
        "",
        f"{len(report.disagreements)} tag disagreements. The first 60:",
        "",
        "| Server | Tool | Axis | Truth | Predicted | Classifier evidence |",
        "|---|---|---|---|---|---|",
        *(
            f"| {d.server} | `{d.tool}` | {d.axis} | {d.truth} | {d.predicted} | "
            f"{d.evidence.replace('|', '/')[:80]} |"
            for d in report.disagreements[:60]
        ),
        "",
        "## Known failure modes",
        "",
        "_To be written by a person after reviewing the disagreements above._",
        "",
    ]
    (out / "results.md").write_text("\n".join(lines), encoding="utf-8")
    (out / "results.json").write_text(
        json.dumps(
            {
                "meta": {**meta, "label_status": dict(meta["label_status"])},
                "classifier": {
                    "tools": report.tools,
                    "unclassified": report.unclassified,
                    "exact_match": report.exact_match,
                    "axes": {a: asdict(m) for a, m in report.axes.items()},
                    "suspicious": asdict(report.suspicious),
                },
                "rule_agreement": {
                    **asdict(agreement),
                    "false_positive_rate": agreement.false_positive_rate,
                },
                "planted": {**asdict(planted), "recall": planted.recall},
                "provisional": bool(provisional),
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--offline", action="store_true", help="classification cache only")
    parser.add_argument("--cache-dir", type=Path, default=EVAL_DIR / ".cache")
    parser.add_argument("--model", help="classifier model (default: built-in / AGENTCAPMAP_MODEL)")
    parser.add_argument("--freeze", action="store_true", help="write labels.lock and exit")
    parser.add_argument("--allow-label-changes", action="store_true")
    parser.add_argument("--out", type=Path, default=EVAL_DIR, help="directory for results files")
    args = parser.parse_args()
    # The runner evaluates many synthetic agents; per-evaluation warnings are noise here.
    logging.getLogger("agentcapmap").setLevel(logging.ERROR)

    servers = load_labeled_servers(LABELS)
    manifest = label_manifest(LABELS)
    if args.freeze:
        LOCK.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        print(f"froze {len(manifest)} label files ({manifest_digest(manifest)[:12]})")
        return 0
    frozen = _check_frozen(manifest, args.allow_label_changes)
    labeled = [s for s in servers if s.labeling.status != "unlabeled"]
    if not labeled:
        sys.exit("no labeled servers yet (see eval/README.md)")

    cache = ClassificationCache(args.cache_dir)
    if args.offline:
        classifier = Classifier(cache, offline=True)
    else:
        from agentcapmap.classify.provider import AnthropicProvider

        classifier = Classifier(cache, AnthropicProvider(model=args.model))

    def classify(tool: ToolDefinition) -> ToolClassification:
        return classifier.classify(tool)

    predictions = {t.definition_hash: classify(t.definition()) for s in labeled for t in s.tools}
    policy = load_policy()
    catalog = {
        s["id"]: s
        for s in json.loads((EVAL_DIR / "catalog.json").read_text(encoding="utf-8"))["servers"]
    }
    agents = json.loads((EVAL_DIR / "agents.json").read_text(encoding="utf-8"))["agents"]

    report = score_classifier(labeled, predictions)
    agreement = rule_agreement(agents, {s.id: s for s in labeled}, catalog, predictions, policy)
    planted = planted_recall(ROOT / "fixtures", classify, policy)
    meta = {
        "date": dt.date.today().isoformat(),
        "tool_version": __version__,
        "model": classifier.model,
        "served_models": sorted({p.model for p in predictions.values() if p.model}),
        "prompt_version": PROMPT_VERSION,
        "taxonomy_version": TAXONOMY_VERSION,
        "servers": len(labeled),
        "label_status": label_status(labeled),
        "frozen": frozen,
        "label_digest": manifest_digest(manifest),
    }
    write_results(out=args.out, report=report, agreement=agreement, planted=planted, meta=meta)
    print(
        f"exact match {_pct(report.exact_match)}, planted recall {_pct(planted.recall)}, "
        f"clean-agent FP rate {_pct(agreement.false_positive_rate)} -> {args.out / 'results.md'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
